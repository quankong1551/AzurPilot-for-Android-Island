/**
 * 默认加载动画指示器尺寸（对齐 Material 3 基础圆环进度条尺寸）
 *
 * Default loading indicator size (matching the baseline Material 3 circular progress indicator size).
 */
val DefaultExpressiveIndicatorSize: Dp = 40.dp

/**
 * Material 3 Expressive 加载动画指示器
 *
 * 遵循 Google Material 3 Expressive 设计规范的动态多边形形变（Shape Morphing）加载动画。
 * 在 7 个标准 Material 几何形态之间通过物理弹簧曲线连续插值，并叠加单步与全局双重旋转。
 * 默认取色绑定 [MaterialTheme.colorScheme.primary]，自动响应深浅色及动态主题切换。
 *
 * Material 3 Expressive loading indicator.
 *
 * A shape-morphing loading animation conforming to Google Material 3 Expressive guidelines.
 * Continuously interpolates across 7 standard Material geometric shapes using an underdamped
 * physical spring curve, composited with step-wise and global rotations.
 * Defaults to [MaterialTheme.colorScheme.primary], automatically adapting to dark/light and
 * dynamic color themes.
 *
 * @param modifier 修饰符，可覆写尺寸（如 `Modifier.size(20.dp)`）
 * @param color 图形填充色，默认取当前 M3 主题的主色
 */
@Composable
fun ExpressiveLoadingIndicator(
    modifier: Modifier = Modifier.size(DefaultExpressiveIndicatorSize),
    color: Color = MaterialTheme.colorScheme.primary,
) {
    var elapsedMs by remember { mutableLongStateOf(0L) }

    // 绑定绘制帧时钟，组件脱离组合树时自动注销取消，无需手动回收
    LaunchedEffect(Unit) {
        val start = withFrameMillis { it }
        while (true) {
            withFrameMillis { frameTime ->
                elapsedMs = frameTime - start
            }
        }
    }

    // 复用单一 Path 对象，避免动画每帧创建对象触发 GC
    val path = remember { Path() }

    val cycleIndex = (elapsedMs / ExpressiveMotion.MORPH_MS).toInt()
    val shapeIndex = cycleIndex % ExpressiveMotion.SHAPE_COUNT
    val localMs = (elapsedMs % ExpressiveMotion.MORPH_MS).toFloat()

    // 物理弹簧阻尼进度计算
    val morph = ExpressiveMotion.springProgress(localMs / 1000f).coerceIn(0f, 1f)

    // 单步旋转叠加全局慢速旋转
    val morphTarget = 90f + (cycleIndex * 90f)
    val globalRotation = ((elapsedMs % ExpressiveMotion.GLOBAL_ROTATION_MS).toFloat() / ExpressiveMotion.GLOBAL_ROTATION_MS) * 360f
    val rotation = morph * 90f + morphTarget + globalRotation

    val shapeA = ExpressiveShapeData.SHAPES[shapeIndex]
    val shapeB = ExpressiveShapeData.SHAPES[shapeIndex + 1]

    Canvas(modifier = modifier) {
        // 48dp 容器中有效直径 38dp（比例 38 / 96 半径比），自适应画布缩放
        val radius = size.minDimension * (38f / 96f)
        val centerX = size.width / 2f
        val centerY = size.height / 2f

        path.reset()
        val count = ExpressiveShapeData.SAMPLE_COUNT
        for (i in 0 until count) {
            val ax = shapeA[i * 2]
            val ay = shapeA[i * 2 + 1]
            val bx = shapeB[i * 2]
            val by = shapeB[i * 2 + 1]
            val px = ax + (bx - ax) * morph
            val py = ay + (by - ay) * morph

            if (i == 0) {
                path.moveTo(px, py)
            } else {
                path.lineTo(px, py)
            }
        }
        path.close()

        // 利用硬件加速绘制矩阵应用变换，减少逐点坐标矩阵计算
        rotate(degrees = rotation, pivot = Offset(centerX, centerY)) {
            translate(left = centerX, top = centerY) {
                scale(scaleX = radius, scaleY = radius, pivot = Offset.Zero) {
                    drawPath(path = path, color = color)
                }
            }
        }
    }
}

private object ExpressiveMotion {
    const val MORPH_MS = 650L
    const val GLOBAL_ROTATION_MS = 4666L
    const val SHAPE_COUNT = 7

    // 二阶欠阻尼系统参数：stiffness = 200, damping ratio = 0.6
    private const val W0 = 14.1421356f
    private const val Z = 0.6f
    private const val WD = 11.3137085f
    private const val K = 0.75f

    fun springProgress(tSeconds: Float): Float {
        if (tSeconds <= 0f) return 0f
        val e = exp(-Z * W0 * tSeconds)
        return 1f - e * (cos(WD * tSeconds) + K * sin(WD * tSeconds))
    }
}

